"""Simple wrapper around QuickJS-NG's qjs-wasi-reactor.wasm."""

import importlib.resources
import json

from wasmjs import lifecycle
from wasmjs import wasmfile


class WasmJS:
    """Simple wrapper around QuickJS-NG's qjs-wasi-reactor.wasm."""

    _wasmfile = None

    def __init__(self):
        if not self._wasmfile:
            WasmJS._wasmfile = wasmfile.WasmFile(wasm=importlib.resources.files(
                'qjs-wasi-reactor').joinpath('qjs-wasi-reactor.wasm').read_bytes())

        self._inst = self._wasmfile.instantiate()
        assert self._inst.exports.memory.pointer_size == 4, (
            'This build of wasmjs assumes JSValues are NaN-boxed int64s.')

        if self._bootstrap:
            with self._inst.api.js.eval_to_jsval(self._bootstrap):
                pass

    _bootstrap = """
      {
        let generators = new Map();
        let next_generator_id = 0;
        let replacer_sentinel = {toJSON() {}};

        function wrap(fn, ...args) {
          try {
            return {value: fn(...args)};
          } catch (error) {
            if (!(error instanceof Error))
              error = new Error(error);
            return {error};
          }
        }

        function replacer(key, value) {
          if (value instanceof Error) {
            let {message, name, stack} = value;
            return {'#': {type: 'Error', message, name, stack, replacer_sentinel}};
          }
          if (Object.prototype.toString.call(value) == '[object Generator]') {
            let id = next_generator_id++;
            generators.set(id, value);
            return {'#': {type: 'Generator', id, replacer_sentinel}};
          }
          if ((key == '#') && (value?.replacer_sentinel !== replacer_sentinel))
            return {value};
          return value;
        }

        globalThis.__wasmjs = {
          eval(expr) {
            let data = wrap(eval, expr);
            return JSON.stringify(data, replacer);
          },

          generator_close(id) {
            let data = {value: generators.delete(id)};
            return JSON.stringify(data, replacer);
          },

          generator_next(id, value) {
            let data = wrap(() => generators.get(id).next(value));
            if (data.error || data.value.done)
              generators.delete(id);
            return JSON.stringify(data, replacer);
          },

          generator_throw(id, value) {
            let error = new Error(value.message);
            error.name = value.name;
            let data = wrap(() => generators.get(id).throw(error));
            if (data.error || data.value.done)
              generators.delete(id);
            if (data.error === error)
              data = {value: {reraise: true}};
            return JSON.stringify(data, replacer);
          },
        };
      }
    """

    def eval(self, expr):
        """Evaluate `expr` as a JavaScript expression."""

        return self._eval(f'__wasmjs.eval({_json_dumps(expr)})')

    def _eval(self, expr):
        try:
            with self._inst.api.js.eval_to_jsval(expr) as jsval:
                datastr = jsval.to_string()
        except wasmfile.wasmtime.Trap as e:
            raise InterpreterError() from e

        data = json.loads(datastr, object_hook=self._object_hook)
        if (error := data.get('error')):
            raise error
        return data.get('value')

    def _object_hook(self, obj):
        if not isinstance(data := obj.get('#'), dict):
            return obj

        match data.pop('type', None):
            case 'Error':
                return JSError(**data)
            case 'Generator':
                return self._run_generator_wrapper(data['id'])
            case objtype:
                assert objtype is None
                obj['#'] = data['value']
                return obj

    def _run_generator_wrapper(self, genid):

        def _close():
            ret = self._eval(f'__wasmjs.generator_close({genid})')
            assert ret

        return lifecycle.run_at_generator_exit(self._run_generator(genid), _close)

    def _run_generator(self, genid):
        incoming = None
        last_exception = None
        method = 'next'
        while True:
            step = self._eval(f'__wasmjs.generator_{method}({genid}, {_json_dumps(incoming)})')
            if step.get('reraise'):
                raise last_exception  # pylint: disable=raising-bad-type
            value = step.get('value')
            if step['done']:
                return value
            try:
                incoming = yield value
                last_exception = None
                method = 'next'
            except Exception as e:  # pylint: disable=broad-exception-caught
                incoming = {
                    'message': str(e),
                    'name': type(e).__name__,
                }
                last_exception = e
                method = 'throw'


class JSError(Exception):
    """Any exception generated by the QuickJS runtime."""

    def __init__(self, *, name, message, stack=None):
        self.name = name
        self.message = message
        self.stack = stack
        super().__init__(f'{name}: {message}')


class InterpreterError(Exception):
    """Any exception generated by the Wasmtime runtime."""


def _json_dumps(val):
    return json.dumps(val, separators=(',', ':'))
